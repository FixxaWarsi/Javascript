// Q1 — Increment / Decrement
var a = 10;

document.write("<h3>Q1 Output — Increment/Decrement</h3>");

document.write("The value of ++a is " + (++a) + "<br>");
document.write("Now the value of a is " + a + "<br>");

document.write("The value of a++ is " + (a++) + "<br>");
document.write("Now the value of a is " + a + "<br>");

document.write("The value of --a is " + (--a) + "<br>");
document.write("Now the value of a is " + a + "<br>");

document.write("The value of a-- is " + (a--) + "<br>");
document.write("Now the value of a is " + a + "<hr>");
